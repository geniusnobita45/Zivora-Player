import { mkdir, readFile, rename, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";

export const MIGRATION_PARTS = [
  "schema/001_auth_catalog_media.sql",
  "indexes/001_auth_catalog_media.sql",
  "policies/001_auth_catalog_media.sql",
  "functions/001_auth_catalog_media.sql",
] as const;

const BuildOptionsSchema = z
  .object({
    databaseRoot: z.string().trim().min(1),
    outputPath: z.string().trim().min(1),
  })
  .strict();

export type BuildMigrationOptions = z.infer<typeof BuildOptionsSchema>;

async function renderLayeredMigration(databaseRoot: string, name: string): Promise<string> {
  const parts = ["schema", "indexes", "functions", "policies"].map(
    (layer) => `${layer}/${name}.sql`,
  );
  const sections = await Promise.all(
    parts.map(
      async (part) =>
        `-- BEGIN ${part}\n${(await readFile(join(databaseRoot, part), "utf8")).trim()}\n-- END ${part}`,
    ),
  );
  return [
    "-- Generated by database/migrations/build.ts. Do not edit this file directly.",
    "begin;",
    ...sections,
    "commit;",
    "",
  ].join("\n\n");
}

export const renderIntelligenceMigration = (databaseRoot: string) =>
  renderLayeredMigration(databaseRoot, "006_intelligence");

export const renderAiMigration = (databaseRoot: string) =>
  renderLayeredMigration(databaseRoot, "007_ai");

export const renderAiRetrievalMigration = (databaseRoot: string) =>
  renderLayeredMigration(databaseRoot, "008_ai_retrieval");

